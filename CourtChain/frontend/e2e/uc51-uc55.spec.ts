import { test, expect } from '@playwright/test'
import { mkdirSync } from 'node:fs'

test('Owner completes UC51–UC55, validation, persistence and responsive UI', async ({ page, request }) => {
  mkdirSync('../docs/screenshots', { recursive: true })
  const errors: string[] = []
  page.on('pageerror', e => errors.push(e.message))
  expect((await request.get('/api/facilities')).status()).toBe(401)
  await page.goto('/')
  await page.screenshot({ path: '../docs/screenshots/login.png', fullPage: true })
  await page.getByLabel('Mật khẩu', { exact: true }).fill(process.env.E2E_PASSWORD!)
  await page.getByRole('button', { name: 'Đăng nhập', exact: true }).click()
  await expect(page.getByText('Xin chào, mình là')).toBeVisible()
  await page.screenshot({ path: '../docs/screenshots/introduction.png', fullPage: true })
  await page.getByRole('link', { name: 'Cơ sở & sân', exact: true }).click()
  await page.getByRole('button', { name: 'Đăng ký cơ sở', exact: true }).first().click()
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('Tên cơ sở').fill('CourtChain Hòa Lạc')
  await dialog.getByLabel('Thành phố / Quận huyện').fill('Hòa Lạc, Hà Nội')
  await dialog.getByLabel('Địa chỉ đầy đủ').fill('1 Đại lộ Thăng Long')
  await dialog.getByLabel('Số điện thoại hotline').fill('0912345678')
  await dialog.getByLabel('Email', { exact: true }).fill('hoalac@example.com')
  await dialog.getByLabel('Bãi đỗ xe').check()
  await dialog.getByRole('button', { name: 'Đăng ký cơ sở', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'CourtChain Hòa Lạc', exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByText('0912345678', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Chỉnh sửa cơ sở', exact: true }).click()
  await dialog.getByLabel('Số điện thoại hotline').fill('0987654321')
  await dialog.getByLabel('Giờ đóng cửa').fill('21:00')
  await dialog.getByLabel('Lý do cập nhật').fill('Điều chỉnh giờ hoạt động và hotline.')
  await dialog.getByLabel('Tôi xác nhận thay đổi giờ hoạt động.').check()
  await dialog.getByRole('button', { name: 'Lưu thay đổi', exact: true }).click()
  await expect(page.getByText('0987654321', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: /Sân thể thao/ }).click()
  for (const [name, sport] of [['Badminton 01', 'Badminton'], ['Badminton 02', 'Badminton'], ['Pickleball 01', 'Pickleball']]) {
    await page.getByRole('button', { name: 'Đăng ký sân mới', exact: true }).first().click()
    await dialog.getByLabel('Tên / số hiệu sân').fill(name)
    await dialog.getByLabel('Môn thể thao').selectOption(sport)
    await dialog.getByRole('button', { name: 'Đăng ký sân', exact: true }).click()
    await expect(page.getByRole('heading', { name, exact: true })).toBeVisible()
  }
  await page.getByRole('button', { name: 'Đăng ký sân mới', exact: true }).first().click()
  await dialog.getByLabel('Tên / số hiệu sân').fill('Badminton 01')
  await dialog.getByRole('button', { name: 'Đăng ký sân', exact: true }).click()
  await expect(dialog.getByRole('alert')).toContainText('đã tồn tại')
  await dialog.getByRole('button', { name: 'Hủy', exact: true }).click()
  await page.locator('.court-card').filter({ has: page.getByRole('heading', { name: 'Badminton 01', exact: true }) }).getByRole('button', { name: 'Chỉnh sửa', exact: true }).click()
  await dialog.getByLabel('Tên sân', { exact: true }).fill('Badminton VIP 01')
  await dialog.getByLabel('Loại mặt sân').selectOption('Rubber')
  await dialog.getByLabel('Trạng thái hoạt động').selectOption('Under Maintenance')
  await dialog.getByLabel('Lý do cập nhật').fill('Bảo trì mặt sân và nâng cấp đèn.')
  await dialog.getByLabel('Tôi xác nhận thay đổi trạng thái sân.').check()
  await dialog.getByRole('button', { name: 'Lưu thay đổi', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Badminton VIP 01' })).toBeVisible()
  await page.screenshot({ path: '../docs/screenshots/courts.png', fullPage: true })
  await page.getByRole('link', { name: 'Chính sách giá', exact: true }).click()
  await page.getByRole('button', { name: 'Tạo chính sách giá', exact: true }).first().click()
  await dialog.getByLabel('Tên chính sách').fill('Giá cầu lông Hòa Lạc')
  await dialog.getByLabel('Giá giờ cao điểm', { exact: true }).fill('90000')
  await dialog.getByRole('button', { name: 'Công bố chính sách' }).click()
  await expect(dialog.getByRole('alert')).toContainText('1,20')
  await dialog.getByLabel('Giá giờ cao điểm', { exact: true }).fill('120000')
  const effective = dialog.getByLabel('Ngày bắt đầu hiệu lực')
  const today = await effective.inputValue()
  await effective.fill('2020-01-01')
  await dialog.getByRole('button', { name: 'Công bố chính sách' }).click()
  await expect(dialog.getByRole('alert')).toContainText('quá khứ')
  await effective.fill(today)
  await dialog.getByRole('button', { name: 'Công bố chính sách' }).click()
  await expect(page.getByRole('heading', { name: 'Giá cầu lông Hòa Lạc' })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Giá cầu lông Hòa Lạc' })).toBeVisible()
  await page.getByRole('button', { name: 'Tạo chính sách giá', exact: true }).click()
  await dialog.getByLabel('Tên chính sách').fill('Giá trùng')
  await dialog.getByRole('button', { name: 'Công bố chính sách' }).click()
  await expect(dialog.getByRole('alert')).toContainText('BR244')
  await dialog.getByRole('button', { name: 'Hủy', exact: true }).click()
  await page.screenshot({ path: '../docs/screenshots/pricing.png', fullPage: true })
  await page.emulateMedia({ colorScheme: 'dark' })
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.screenshot({ path: '../docs/screenshots/mobile.png', fullPage: true })
  expect(errors).toEqual([])
})
